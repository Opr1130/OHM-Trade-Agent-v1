@pytest.mark.acceptance
def test_t20_symlinked_critical_path_is_refused(tmp_path):
    """ATDD-OPIP-LEARNING-RECOVERY-v1/AC-019: T20: symlink substitution into a critical path is rejected."""
    repo, production, tooling = _repo(tmp_path)
    manifest = prepare(
        production_sha=production,
        tooling_sha=tooling,
        repo_root=repo,
        exceptions_file=_exceptions(tmp_path, production, tooling, [CONSUMER]),
    )
    committed = dict(manifest["tooling_sha256"])
    outside = tmp_path / "outside.py"
    outside.write_bytes(b"VERSION = 99\n")
    target = repo / CONSUMER
    target.unlink()
    try:
        target.symlink_to(outside)
    except (OSError, NotImplementedError):
        pytest.skip("symlink creation not permitted on this platform")
    # A release-tree walk must never follow a link out of the root.
    with pytest.raises(ValueError, match="symlink"):
        _expand_fs(repo)
    # The committed inventory is a property of the commit, not the working tree.
    assert _expand_tracked(repo, tooling) == committed
    # Verification of a symlinked release tree fails closed.
    checks = verify(
        manifest=manifest,
        source_app=repo,
        production_sha=production,
        tooling_sha=tooling,
    )
    assert "compatibility_hashes_match" in {
        check["name"] for check in checks if not check["passed"]
    }


@pytest.mark.acceptance
def test_t21_release_tree_without_git_still_verifies(tmp_path):
    """ATDD-OPIP-LEARNING-RECOVERY-v1/AC-019: T21: the staged archive has no .git and must still verify exactly."""
    repo, production, tooling = _repo(tmp_path)
    manifest = prepare(
        production_sha=production,
        tooling_sha=tooling,
        repo_root=repo,
        exceptions_file=_exceptions(tmp_path, production, tooling, [CONSUMER]),
    )
    archive = tmp_path / "release.tar"
    with archive.open("wb") as handle:
        subprocess.run(
            ["git", "-C", str(repo), "archive", "--format=tar", tooling],
            stdout=handle,
            check=True,
        )
    release = tmp_path / "release"
    release.mkdir()
    with tarfile.open(archive) as tar:
        tar.extractall(release, filter="data")
    assert not (release / ".git").exists()
    checks = verify(
        manifest=manifest,
        source_app=release,
        production_sha=production,
        tooling_sha=tooling,
    )
    failures = [check for check in checks if not check["passed"] and check["name"] != "attestation_present"]
    assert failures == []


