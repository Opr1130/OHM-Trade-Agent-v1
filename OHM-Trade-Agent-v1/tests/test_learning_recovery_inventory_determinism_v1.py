@pytest.mark.acceptance
def test_inventory_is_stable_across_repeated_prepare_calls(tmp_path):
    """ATDD-OPIP-LEARNING-RECOVERY-v1/AC-019: Determinism: repeated prepare runs must yield byte-identical hash maps."""
    repo, production, tooling = _repo(tmp_path)
    exceptions = _exceptions(tmp_path, production, tooling, [CONSUMER])
    first = prepare(
        production_sha=production,
        tooling_sha=tooling,
        repo_root=repo,
        exceptions_file=exceptions,
    )
    (repo / "app" / "opip" / "learning" / "__pycache__").mkdir(exist_ok=True)
    (repo / "app" / "opip" / "learning" / "__pycache__" / "x.pyc").write_bytes(b"z")
    second = prepare(
        production_sha=production,
        tooling_sha=tooling,
        repo_root=repo,
        exceptions_file=exceptions,
    )
    assert first["tooling_sha256"] == second["tooling_sha256"]
    assert hashlib.sha256(
        json.dumps(first["tooling_sha256"], sort_keys=True).encode()
    ).hexdigest() == hashlib.sha256(
        json.dumps(second["tooling_sha256"], sort_keys=True).encode()
    ).hexdigest()

