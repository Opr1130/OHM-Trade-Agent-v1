"""Cross-SHA compatibility for recovery worker tooling.

Recovery builds worker code from a newer tooling SHA while binding the release
identity to the running production SHA. That is safe only when every learning
consumer/runtime contract is either byte-identical or explicitly certified.

Critical paths cover canonical storage, learning jobs/readiness, phase-3C
outcomes and the production evidence exporter/reader. Any change between the
production SHA and the tooling SHA must appear in an owner-approved exception
file for that exact SHA pair. The worker re-verifies every tooling file hash
from the manifest generated by the trusted workflow.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

from app.services.learning_recovery_attestation import (
    validate_manifest_attestation,
)


CRITICAL_PATHS = (
    # Derived from deploy/learning/opip-learning-job.sh and the modules it runs:
    # capture/reconcile -> run_opip_ml_capture; outcomes ->
    # run_opportunity_intelligence_cycle (which drives discovery and Phase-3C
    # outcomes); readiness -> run_opip_ml_data_readiness.
    "app/jobs/run_opip_ml_capture.py",
    "app/jobs/reconcile_discovery_accountability_evidence.py",
    "app/jobs/run_opportunity_intelligence_cycle.py",
    "app/jobs/build_discovery_forward_outcomes.py",
    "app/jobs/build_phase3c_forward_outcomes.py",
    "app/jobs/run_opip_ml_data_readiness.py",
    "app/services/opip_ml_evidence_capture.py",
    "app/services/opportunity_accountability.py",
    "app/services/phase3c_outcomes.py",
    "app/services/registry_io.py",
    "app/opip/canonical",
    "app/opip/learning",
    "app/opip/discovery",
    "app/opip/decision/store.py",
    "app/opip/storage/bounded_jsonl.py",
    "app/scanner/candidates.py",
    "deploy/remote/export-opip-learning-evidence.sh",
    "deploy/remote/opip-learning-read-export.sh",
    "deploy/learning/opip-learning-job.sh",
)


def critical_paths() -> tuple[str, ...]:
    return CRITICAL_PATHS


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _expand(root: Path) -> dict[str, str]:
    hashes: dict[str, str] = {}
    for entry in CRITICAL_PATHS:
        path = root / entry
        if path.is_file():
            hashes[entry] = _sha256(path)
        elif path.is_dir():
            for child in sorted(path.rglob("*")):
                if child.is_file() and not child.is_symlink():
                    hashes[str(child.relative_to(root))] = _sha256(child)
    return hashes


def _exceptions(
    path: Path, production_sha: str, tooling_sha: str
) -> tuple[set[str], str]:
    if not path.is_file():
        return set(), ""
    payload = json.loads(path.read_text(encoding="utf-8"))
    pair = payload.get("pairs", {}).get(f"{production_sha}..{tooling_sha}", {})
    return set(pair.get("paths") or []), str(pair.get("rationale") or "")


def evaluate(
    *,
    production_sha: str,
    tooling_sha: str,
    changed_critical_paths: list[str],
    approved_paths: set[str],
) -> tuple[bool, list[str]]:
    if not changed_critical_paths:
        return True, []
    unreviewed = sorted(set(changed_critical_paths) - approved_paths)
    return (not unreviewed), unreviewed


def _repo_prefix(repo_root: Path) -> str:
    """Return the app-root prefix relative to the git top-level, if any."""
    result = subprocess.run(
        ["git", "-C", str(repo_root), "rev-parse", "--show-toplevel"],
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        return ""
    top = Path(result.stdout.strip()).resolve()
    root = Path(repo_root).resolve()
    try:
        relative = root.relative_to(top).as_posix()
    except ValueError:
        return ""
    return "" if relative == "." else f"{relative}/"


def _strip_prefix(path: str, prefix: str) -> str:
    value = path.strip().replace("\\", "/")
    if prefix and value.startswith(prefix):
        return value[len(prefix) :]
    return value


def prepare(
    *,
    production_sha: str,
    tooling_sha: str,
    repo_root: Path,
    exceptions_file: Path,
) -> dict:
    prefix = _repo_prefix(repo_root)
    result = subprocess.run(
        [
            "git",
            "-C",
            str(repo_root),
            "diff",
            "--name-only",
            production_sha,
            tooling_sha,
            "--",
            *CRITICAL_PATHS,
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        raise ValueError(f"git diff failed: {result.stderr.strip()}")
    changed = sorted(
        _strip_prefix(line, prefix)
        for line in result.stdout.splitlines()
        if line.strip()
    )
    approved, rationale = _exceptions(exceptions_file, production_sha, tooling_sha)
    approved = {_strip_prefix(path, prefix) for path in approved}
    passed, unreviewed = evaluate(
        production_sha=production_sha,
        tooling_sha=tooling_sha,
        changed_critical_paths=changed,
        approved_paths=approved,
    )
    return {
        "schema": "opip-learning-recovery-compatibility/v1",
        "status": "PASS" if passed else "REFUSED",
        "production_sha": production_sha,
        "tooling_sha": tooling_sha,
        "critical_paths": list(CRITICAL_PATHS),
        "changed_critical_paths": changed,
        "approved_paths": sorted(approved),
        "unreviewed_changes": unreviewed,
        "attestation_required": not passed,
        "exception_rationale": rationale,
        "tooling_sha256": _expand(repo_root),
    }


def verify(
    *,
    manifest: dict,
    source_app: Path,
    production_sha: str,
    tooling_sha: str,
) -> list[dict]:
    checks: list[dict] = []

    def add(name: str, passed: bool, detail: str) -> None:
        checks.append({"name": name, "passed": bool(passed), "detail": detail})

    add(
        "compatibility_status",
        manifest.get("status") == "PASS",
        str(manifest.get("status")),
    )
    add(
        "compatibility_production_sha",
        manifest.get("production_sha") == production_sha,
        f"manifest={manifest.get('production_sha')}",
    )
    add(
        "compatibility_tooling_sha",
        manifest.get("tooling_sha") == tooling_sha,
        f"manifest={manifest.get('tooling_sha')}",
    )
    add(
        "no_unreviewed_critical_changes",
        not manifest.get("unreviewed_changes"),
        f"unreviewed={manifest.get('unreviewed_changes')}",
    )
    expected = manifest.get("tooling_sha256") or {}
    add("compatibility_hash_manifest_present", bool(expected), f"files={len(expected)}")
    mismatched = []
    for relative, digest in expected.items():
        path = source_app / relative
        if not path.is_file() or _sha256(path) != digest:
            mismatched.append(relative)
    add("compatibility_hashes_match", not mismatched, f"mismatched={mismatched}")
    if manifest.get("attestation_required") or (
        manifest.get("changed_critical_paths") and not manifest.get("approved_paths")
    ):
        checks.extend(validate_manifest_attestation(manifest))
    return checks


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Recovery compatibility")
    sub = parser.add_subparsers(dest="command", required=True)

    paths_parser = sub.add_parser("paths")
    paths_parser.add_argument("--json", action="store_true")

    prep = sub.add_parser("prepare")
    prep.add_argument("--production-sha", required=True)
    prep.add_argument("--tooling-sha", required=True)
    prep.add_argument("--repo-root", required=True)
    prep.add_argument("--exceptions-file", required=True)
    prep.add_argument("--out", required=True)

    verify_parser = sub.add_parser("verify")
    verify_parser.add_argument("--manifest", required=True)
    verify_parser.add_argument("--source-app", required=True)
    verify_parser.add_argument("--production-sha", required=True)
    verify_parser.add_argument("--tooling-sha", required=True)

    args = parser.parse_args(argv)
    if args.command == "paths":
        print(
            json.dumps(list(CRITICAL_PATHS))
            if args.json
            else "\n".join(CRITICAL_PATHS)
        )
        return 0
    if args.command == "prepare":
        payload = prepare(
            production_sha=args.production_sha,
            tooling_sha=args.tooling_sha,
            repo_root=Path(args.repo_root),
            exceptions_file=Path(args.exceptions_file),
        )
        out = Path(args.out)
        out.write_text(json.dumps(payload, indent=2, sort_keys=True), encoding="utf-8")
        print(json.dumps({"status": payload["status"], "out": str(out)}))
        return 0 if payload["status"] == "PASS" else 2
    manifest = json.loads(Path(args.manifest).read_text(encoding="utf-8"))
    checks = verify(
        manifest=manifest,
        source_app=Path(args.source_app),
        production_sha=args.production_sha,
        tooling_sha=args.tooling_sha,
    )
    failures = [check for check in checks if not check["passed"]]
    for check in checks:
        print(
            f"{'PASS' if check['passed'] else 'FAIL'} "
            f"{check['name']} {check['detail']}"
        )
    return 0 if not failures else 2


if __name__ == "__main__":
    sys.exit(main())
